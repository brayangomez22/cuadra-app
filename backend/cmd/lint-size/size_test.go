package main

import (
	"strings"
	"testing"
	"testing/fstest"

	"github.com/stretchr/testify/require"
)

// lines returns n lines of Go source.
func lines(n int) *fstest.MapFile {
	return &fstest.MapFile{Data: []byte(strings.Repeat("x := 1\n", n))}
}

func generated(n int) *fstest.MapFile {
	header := "// Code generated by sqlc. DO NOT EDIT.\n"
	return &fstest.MapFile{Data: []byte(header + strings.Repeat("x := 1\n", n-1))}
}

func testRules() Rules {
	return Rules{MaxLines: 10, MaxTestLines: 15}
}

func scan(t *testing.T, fsys fstest.MapFS, rules Rules) Result {
	t.Helper()
	result, err := Scan(fsys, rules)
	require.NoError(t, err)
	return result
}

func TestScan(t *testing.T) {
	t.Run("reporta un archivo de código que pasa del límite, con sus líneas", func(t *testing.T) {
		fsys := fstest.MapFS{
			"internal/catalog/product.go": lines(11),
			"internal/catalog/unit.go":    lines(10),
		}

		result := scan(t, fsys, testRules())

		require.Equal(t, []Finding{{Path: "internal/catalog/product.go", Lines: 11, Max: 10}}, result.Findings)
	})

	t.Run("cuenta la última línea aunque no termine en salto de línea", func(t *testing.T) {
		fsys := fstest.MapFS{
			"a.go": {Data: []byte(strings.Repeat("x := 1\n", 10) + "y := 2")},
		}

		result := scan(t, fsys, testRules())

		require.Equal(t, []Finding{{Path: "a.go", Lines: 11, Max: 10}}, result.Findings)
	})

	t.Run("aplica a los tests su propio límite", func(t *testing.T) {
		fsys := fstest.MapFS{
			"sale_test.go":  lines(15),
			"stock_test.go": lines(16),
		}

		result := scan(t, fsys, testRules())

		require.Equal(t, []Finding{{Path: "stock_test.go", Lines: 16, Max: 15}}, result.Findings)
	})

	t.Run("ignora el código generado, testdata, vendor y lo que no es Go", func(t *testing.T) {
		fsys := fstest.MapFS{
			"api/catalogapi/api.gen.go":   lines(50),
			"postgres/sqlcgen/queries.go": lines(50),
			"postgres/models.go":          generated(50),
			"testdata/big.go":             lines(50),
			"vendor/lib/lib.go":           lines(50),
			"postgres/queries.sql":        lines(50),
		}

		result := scan(t, fsys, testRules())

		require.Empty(t, result.Findings)
	})

	t.Run("no considera generado un archivo que solo menciona el encabezado más abajo", func(t *testing.T) {
		data := "package main\n\n// Code generated by sqlc. DO NOT EDIT.\n" + strings.Repeat("x := 1\n", 10)
		fsys := fstest.MapFS{"main.go": {Data: []byte(data)}}

		result := scan(t, fsys, testRules())

		require.Equal(t, []Finding{{Path: "main.go", Lines: 13, Max: 10}}, result.Findings)
	})

	t.Run("deja pasar un archivo de la lista temporal mientras siga pasado del límite", func(t *testing.T) {
		rules := testRules()
		rules.Allow = []string{"internal/catalog/product.go"}
		fsys := fstest.MapFS{"internal/catalog/product.go": lines(30)}

		result := scan(t, fsys, rules)

		require.Empty(t, result.Findings)
		require.Empty(t, result.Unused)
	})

	t.Run("pide quitar de la lista temporal un archivo que ya cumple o no existe", func(t *testing.T) {
		rules := testRules()
		rules.Allow = []string{"internal/catalog/product.go", "internal/gone.go"}
		fsys := fstest.MapFS{"internal/catalog/product.go": lines(9)}

		result := scan(t, fsys, rules)

		require.Empty(t, result.Findings)
		require.Equal(t, []string{"internal/catalog/product.go", "internal/gone.go"}, result.Unused)
	})
}
